import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { BASE, call, cleanup, signIn } from "./client.ts";
import type { ReviewSnapshot, Branch } from "../src/review/types.ts";

const trunk = `stacks-${Date.now().toString(36)}`, api = `/api/trunks/${trunk}`;
const root = mkdtempSync(join(tmpdir(), "nanohub-stacks-"));
const cookie = await signIn("stack-owner");
const other = await signIn("stack-other");
const git = (...args: string[]) => execFileSync("git", ["-c", "credential.helper=", "-C", root, ...args], { encoding: "utf8", stdio: "pipe", env: { ...process.env, GIT_TERMINAL_PROMPT: "0" } }).trim();
const get = () => call<ReviewSnapshot>("GET", `${api}/pulls`, undefined, cookie);
const post = (path: string, body: unknown) => call<ReviewSnapshot>("POST", api + path, body, cookie);
const check = (label: string) => console.log(`ok  ${label}`);
let tokenId: string | undefined;
try {
  await call("POST", api, { files: [{ path: "README.md", text: "Stack fixture\n" }] }, cookie);
  const token = await call<{ token: string; id: string }>("POST", "/api/tokens", { label: "stack test", trunk }, cookie);
  tokenId = token.id;
  const remote = `${BASE}/git/${trunk}.git`;
  const auth = `Authorization: Basic ${Buffer.from(`tester:${token.token}`).toString("base64")}`;
  git("-c", `http.extraHeader=${auth}`, "clone", "-q", remote, ".");
  git("config", "user.name", "stack-test"); git("config", "user.email", "stack@test.invalid");
  const push = (name: string, force = false) => git("-c", `http.extraHeader=${auth}`, "push", ...(force ? ["--force-with-lease"] : []), "origin", `HEAD:refs/heads/${name}`);
  const add = (path: string, text: string) => { writeFileSync(join(root, path), text); git("add", path); git("commit", "-qm", `Update ${path}`); };
  git("switch", "-qc", "feature/schema"); add("schema.txt", "schema one\n"); push("feature/schema");
  let s = await post("/pulls", { title: "Schema", head: "feature/schema", base: "main" });
  const parent = s.pulls[0].number;
  assert.deepEqual(Object.keys(s.pulls[0].author).sort(), ["id", "name"]);
  git("switch", "-qc", "feature/api"); add("api.txt", "api one\n"); push("feature/api");
  s = await post("/pulls", { title: "API", head: "feature/api", base: "feature/schema" });
  const child = s.pulls[0].number;
  const detail = (n: number) => call<ReviewSnapshot & { files: { path: string }[]; head: Branch }>("GET", `${api}/pulls/${n}`, undefined, cookie);
  const observed = async (n: number) => { const d = await detail(n); return { commit: d.head.commit, anchor: d.pulls.find((p) => p.number === n)!.anchor }; };
  assert.deepEqual((await detail(child)).files.map((f) => f.path), ["api.txt"]);
  check("stacked PR shows only its own file");
  await assert.rejects(post(`/pulls/${child}/merge`, await observed(child)), /parent PR/);
  assert.equal((await call<{ version: number }>("GET", api, undefined, cookie)).version, 1);
  check("branch pushes do not land and child cannot merge before parent");
  await assert.rejects(post(`/pulls/${parent}/merge`, { commit: "0".repeat(40), anchor: "0".repeat(40) }), /changed/);
  check("stale review heads cannot merge");
  git("switch", "-q", "feature/schema"); add("schema.txt", "schema two\n"); push("feature/schema");
  await post(`/pulls/${child}/restack`, await observed(child));
  assert.deepEqual((await detail(child)).files.map((f) => f.path), ["api.txt"]);
  check("child restacks onto an updated parent without inheriting its diff");
  await post(`/pulls/${parent}/reviews`, { ...await observed(parent), verdict: "REQUEST_CHANGES", body: "Add docs" });
  await assert.rejects(post(`/pulls/${parent}/merge`, await observed(parent)), /requested changes/);
  await post(`/pulls/${parent}/reviews`, { ...await observed(parent), verdict: "APPROVE", body: "Ready" });
  const parentObserved = await observed(parent);
  s = await post(`/pulls/${parent}/merge`, parentObserved);
  assert.equal(s.pulls.find((p) => p.number === parent)!.state, "merged");
  assert.equal(s.pulls.find((p) => p.number === child)!.base, "main");
  await post(`/pulls/${parent}/merge`, parentObserved);
  assert.equal((await call<{ version: number }>("GET", api, undefined, cookie)).version, 2);
  check("reviews block merge, parent merges once, child retargets to main");
  await post(`/pulls/${child}/restack`, await observed(child));
  assert.deepEqual((await detail(child)).files.map((f) => f.path), ["api.txt"]);
  const childObserved = await observed(child);
  const mergedTwice = await Promise.allSettled([post(`/pulls/${child}/merge`, childObserved), post(`/pulls/${child}/merge`, childObserved)]);
  assert.ok(mergedTwice.some((r) => r.status === "fulfilled"));
  assert.equal((await call<{ version: number }>("GET", api, undefined, cookie)).version, 3);
  git("-c", `http.extraHeader=${auth}`, "fetch", "origin");
  git("fsck", "--strict");
  assert.equal(git("show", "origin/main:api.txt"), "api one");
  assert.equal(git("show", "origin/main:schema.txt"), "schema two");
  check("restacking preserves incremental diff; main contains both changes and Git integrity holds");
  await post("/branches", { name: "conflict", from: "main" });
  git("switch", "-qc", "conflict", "origin/main"); add("schema.txt", "branch edit\n"); push("conflict");
  s = await post("/pulls", { title: "Conflict", head: "conflict" });
  const conflict = s.pulls[0].number;
  git("switch", "-q", "main"); git("reset", "--hard", "origin/main"); add("schema.txt", "main edit\n"); push("main");
  const before = (await get()).branches.find((b) => b.name === "conflict")!.commit;
  await assert.rejects(post(`/pulls/${conflict}/restack`, await observed(conflict)), /conflicts/);
  assert.equal((await get()).branches.find((b) => b.name === "conflict")!.commit, before);
  check("conflicting restack leaves branch unchanged");
  await assert.rejects(call("DELETE", `${api}/branches`, { name: "conflict", commit: before }, cookie), /open PRs/);
  await assert.rejects(post("/branches", { name: "../bad" }), /Invalid branch/);
  await call("POST", `${api}-private`, { visibility: "private", files: [{ path: "README.md", text: "private\n" }] }, cookie);
  for (const denied of [undefined, other]) {
    const res = await fetch(BASE + `${api}-private/pulls`, { headers: denied ? { cookie: denied } : {} });
    assert.equal(res.status, 404);
  }
  check("open branches cannot be deleted and private reviews reject other users");
  await call("POST", `${api}-private/agents`, { handle: "review-agent", type: "Codex" }, cookie);
  const scoped = await call<{ token: string; id: string }>("POST", `${api}-private/agents/review-agent/token`, {}, cookie);
  const agentHeaders = { authorization: `Basic ${Buffer.from(`review-agent:${scoped.token}`).toString("base64")}`, "content-type": "application/json" };
  const scopedBranch = await fetch(BASE + `${api}-private/branches`, { method: "POST", headers: agentHeaders, body: JSON.stringify({ name: "agent/review", from: "main" }) });
  assert.equal(scopedBranch.status, 200);
  await call("DELETE", `/api/tokens/${scoped.id}`, undefined, cookie);
  const crossOrigin = await fetch(BASE + `${api}/branches`, { method: "POST", headers: { cookie, origin: "https://unrelated.invalid", "content-type": "application/json" }, body: JSON.stringify({ name: "not-created" }) });
  assert.equal(crossOrigin.status, 403);
  const raced = await Promise.allSettled([post("/branches", { name: "race" }), post("/branches", { name: "race" })]);
  assert.equal(raced.filter((r) => r.status === "fulfilled").length, 1);
  check("scoped agents can create private branches; cross-origin writes and concurrent duplicate refs are rejected");
  git("-c", `http.extraHeader=${auth}`, "fetch", "origin");
  git("switch", "-q", "conflict"); git("reset", "--hard", "origin/main");
  add("schema.txt", "resolved schema\n"); push("conflict", true);
  const resolved = await detail(conflict);
  assert.equal(resolved.pulls.find((p) => p.number === conflict)!.anchor, resolved.branches.find((b) => b.name === "main")!.commit);
  assert.deepEqual(resolved.files.map((f) => f.path), ["schema.txt"]);
  check("a local rebase and force-with-lease push update the PR's comparison anchor");
  git("-c", `http.extraHeader=${auth}`, "push", "origin", "--delete", "race");
  assert.ok(!(await get()).branches.some((b) => b.name === "race"));
  check("ordinary git branch deletion uses the advertised ref capability");
  await post(`/pulls/${conflict}/close`, {});
  await call("DELETE", `${api}/branches`, { name: "conflict", commit: resolved.head.commit }, cookie);
  assert.equal((await detail(conflict)).files[0].path, "schema.txt");
  check("closed PR diff survives branch deletion");
} finally {
  if (tokenId) await call("DELETE", `/api/tokens/${tokenId}`, undefined, cookie);
  await call("DELETE", `${api}-private`, undefined, cookie).catch(() => {});
  await cleanup([trunk]);
  rmSync(root, { recursive: true, force: true });
}
