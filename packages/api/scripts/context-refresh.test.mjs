import assert from "node:assert/strict";
import { DatabaseSync } from "node:sqlite";
import { build } from "esbuild";
const output = await build({entryPoints:['src/room/github-context.ts'], bundle:true, write:false, format:'esm', platform:'node'});
const {refreshContext} = await import(`data:text/javascript;base64,${Buffer.from(output.outputFiles[0].text).toString('base64')}`);
const db = new DatabaseSync(':memory:');
db.exec(`CREATE TABLE meta(k TEXT PRIMARY KEY,v TEXT NOT NULL);
CREATE TABLE issues(number INTEGER PRIMARY KEY,title TEXT,body TEXT,origin TEXT,upstream TEXT,state TEXT,labels TEXT,author TEXT,created INTEGER,comments INTEGER,url TEXT,landed INTEGER DEFAULT 0,closed_by TEXT,closed_in INTEGER);`);
const sql={exec(query,...args){const stmt=db.prepare(query);const rows=/^SELECT/.test(query.trim()) ? stmt.all(...args) : (stmt.run(...args),[]); return {toArray:()=>rows};}};
const repo={fullName:'owner/repo',commit:'original-sha',pulls:[],importSummary:{files:12,skipped:2,notes:['old failure'],importedAt:123}};
db.prepare('INSERT INTO meta VALUES (?,?)').run('repo',JSON.stringify(repo));
const issue=(number)=>({number,title:`Updated ${number}`,body:'context',origin:'github',upstream:'open',labels:[],author:'upstream',created:1,comments:3,url:`https://github.com/owner/repo/issues/${number}`});
refreshContext(sql,repo,[issue(1),issue(2)],[]);
db.exec("UPDATE issues SET state='closed',landed=4,closed_by='builder',closed_in=7 WHERE number=1; UPDATE issues SET origin='local',title='Local task' WHERE number=2");
const next=refreshContext(sql,{...repo,commit:'new-sha'},[issue(1),issue(2),issue(3)],[]);
assert.deepEqual({...db.prepare('SELECT state,landed,closed_by,closed_in,title FROM issues WHERE number=1').get()}, {state:'closed',landed:4,closed_by:'builder',closed_in:7,title:'Updated 1'});
assert.equal(db.prepare('SELECT title FROM issues WHERE number=2').get().title,'Local task');
assert.equal(db.prepare('SELECT title FROM issues WHERE number=3').get().title,'Updated 3');
assert.equal(next.commit,'original-sha');
assert.equal(next.importSummary.files,12);
assert.equal(next.importSummary.importedAt,123);
assert.ok(next.contextNotes.some(n=>n.includes('#2')));
assert.ok(!next.contextNotes.includes('old failure'));
assert.throws(()=>refreshContext(sql,{...repo,fullName:'other/repo'},[],[]),/does not match/);
db.close();
console.log('PASS: refresh retains seed, local tasks, agent work and closures; adds upstream issues and clears stale errors');
